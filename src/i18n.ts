import { moment } from "obsidian";

type Lang = "ko" | "en";
let current: Lang = "en";

export function setLanguage(pref: "auto" | "ko" | "en") {
	if (pref === "auto") current = moment.locale().startsWith("ko") ? "ko" : "en";
	else current = pref;
}

export function lang(): Lang {
	return current;
}

